"""Build scene timing from measured narration durations so the film lands on exactly 900 s.
Writes story/timing.json and src/data/timing.ts."""
import json, os
FPS, TARGET = 30, 900
LEAD, TAIL = 0.6, 0.8
ACT_OPEN_EXTRA = {'S03': 2.0, 'S15': 2.0, 'S28': 2.0}
script = json.load(open('story/script.json', encoding='utf-8'))
durs = json.load(open('story/narration_durations.json'))
rows, total = [], 0.0
for s in script['scenes']:
    if s['narration']:
        lead = LEAD + ACT_OPEN_EXTRA.get(s['id'], 0) + s.get('preSilence', 0)
        sec = lead + durs[s['id']] + TAIL + s.get('breakAfter', 0)
    else:
        lead, sec = 0, s['fixedSeconds']
    rows.append({'id': s['id'], 'act': s['act'], 'title': s['title'], 'lead': lead, 'narr': durs.get(s['id'], 0), 'sec': sec})
    total += sec
rows[-1]['sec'] += TARGET - total  # absorb remainder in the end credits
frame = 0
for r in rows:
    r['frames'] = round(r['sec'] * FPS)
    r['from'] = frame
    r['narrFrom'] = round(r['lead'] * FPS)
    r['narrFrames'] = round(r['narr'] * FPS)
    frame += r['frames']
rows[-1]['frames'] += TARGET * FPS - frame
json.dump({'fps': FPS, 'totalFrames': TARGET * FPS, 'scenes': rows}, open('story/timing.json', 'w'), ensure_ascii=False, indent=1)
os.makedirs('src/data', exist_ok=True)
with open('src/data/timing.ts', 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/timing.py — do not edit by hand.\n')
    f.write('export const FPS = 30;\nexport const TOTAL_FRAMES = %d;\n' % (TARGET * FPS))
    f.write('export type SceneTiming = {id: string; act: number; from: number; frames: number; narrFrom: number; narrFrames: number};\n')
    f.write('export const TIMING: Record<string, SceneTiming> = {\n')
    for r in rows:
        f.write(f"  {r['id']}: {{id: '{r['id']}', act: {r['act']}, from: {r['from']}, frames: {r['frames']}, narrFrom: {r['narrFrom']}, narrFrames: {r['narrFrames']}}},\n")
    f.write('};\nexport const SCENE_IDS = Object.keys(TIMING);\n')
print('end credits', round(rows[-1]['sec'], 2), 's; total frames', sum(r['frames'] for r in rows))
for r in rows: print(r['id'], r['frames'], round(r['frames'] / FPS, 1))
