"""Estimate per-word start times in each narration clip.
Punctuation marks are aligned (in order) to the most prominent silent gaps detected in the audio;
words inside each segment are spread by character count. Output: src/data/cues.ts"""
import json, re, numpy as np, soundfile as sf

FPS = 30
DIAC = re.compile(r'[ً-ْٰ]')
PUNCT = '،.:؛…؟!'
timing = {s['id']: s for s in json.load(open('story/timing.json'))['scenes']}
script = json.load(open('story/script.json', encoding='utf-8'))
out = {}
for sc in script['scenes']:
    if not sc['narration']: continue
    x, sr = sf.read(f'audio/narration/{sc["id"]}.wav')
    hop = int(sr * 0.01)
    e = np.array([np.sqrt(np.mean(x[i:i + hop] ** 2)) for i in range(0, len(x) - hop, hop)])
    thr = max(1e-4, np.percentile(e, 95) * 0.06)
    quiet = e < thr
    gaps = []  # (start_s, end_s)
    i = 0
    while i < len(quiet):
        if quiet[i]:
            j = i
            while j < len(quiet) and quiet[j]: j += 1
            if (j - i) >= 12: gaps.append((i / 100, j / 100))
            i = j
        else: i += 1
    dur = len(x) / sr
    gaps = [g for g in gaps if 0.2 < g[0] < dur - 0.4]
    text = DIAC.sub('', sc['narration'])
    tokens = text.split()
    # segment boundaries: after tokens ending with punctuation (except the last)
    seg_ends = [k for k, tk in enumerate(tokens[:-1]) if tk[-1] in PUNCT]
    n = min(len(seg_ends), len(gaps))
    chosen = sorted(sorted(gaps, key=lambda g: g[1] - g[0], reverse=True)[:n])
    # if fewer gaps than punctuation, keep the boundaries with the strongest punctuation
    if n < len(seg_ends):
        prio = {'.': 3, '؟': 3, '…': 3, ':': 2, '،': 1}
        seg_ends = sorted(sorted(seg_ends, key=lambda k: -prio.get(tokens[k][-1], 1))[:n])
    bounds = [0.05] + [g[1] for g in chosen] + [dur]
    ends_t = [0.0] + [g[0] for g in chosen] + [dur - 0.3]
    segs, start = [], 0
    for k in seg_ends + [len(tokens) - 1]:
        segs.append(tokens[start:k + 1]); start = k + 1
    words = []
    for si, seg in enumerate(segs):
        t0, t1 = bounds[si], ends_t[si + 1]
        lens = np.array([len(w) + 1 for w in seg], float)
        cum = np.concatenate([[0], np.cumsum(lens)[:-1]]) / lens.sum()
        for w, c in zip(seg, cum):
            words.append([re.sub(f'[{PUNCT}«»]', '', w), round(t0 + c * (t1 - t0), 2)])
    out[sc['id']] = {'offset': timing[sc['id']]['narrFrom'], 'words': words}
with open('src/data/cues.ts', 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/cues.py — estimated word start times (seconds, relative to narration start).\n')
    f.write('export const CUES: Record<string, {offset: number; words: [string, number][]}> = ')
    f.write(json.dumps(out, ensure_ascii=False))
    f.write(';\n')
print({k: len(v['words']) for k, v in list(out.items())[:5]})
