// Embeds blender/build_scene.py into js/87-blender-py.js (the app ships it inside the Blender package).
// Run after editing the Python script:  node terramind-studio/tools/embed-blender.js
const fs = require('fs'), path = require('path'); const ROOT = path.join(__dirname, '..');
const py = fs.readFileSync(path.join(ROOT, 'blender', 'build_scene.py'), 'utf8');
fs.writeFileSync(path.join(ROOT, 'js', '87-blender-py.js'), `/* Generated by tools/embed-blender.js from blender/build_scene.py — do not edit by hand. */\n(function (TM) { TM.BlenderPy = ${JSON.stringify(py)}; })(typeof window !== 'undefined' ? window.TM : globalThis.TM);\n`);
console.log('embedded', py.length, 'chars');
